import JSZip from 'jszip'

const ZIP_COMMENT = 'Generated by https://replaypacker.zeta-two.com'

export type ZipFile = { name: string; content: Blob }

// Padding bytes, then the padding length as a uint32 and a trailer naming the padding kind
export function padBlob(base: Blob, paddingLength: number, trailer: string) {
  return new Blob([
    base,
    new Uint8Array(paddingLength).fill(0xaa),
    new Uint32Array([paddingLength]),
    trailer
  ])
}

export function generateZip(files: ZipFile[]) {
  const zip = new JSZip()
  for (const file of files) {
    zip.file(file.name, file.content)
  }
  return zip.generateAsync({
    type: 'blob',
    comment: ZIP_COMMENT,
    compression: 'DEFLATE',
    compressionOptions: { level: 6 }
  })
}
