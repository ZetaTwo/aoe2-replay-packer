import { describe, it, expect } from 'vitest'
import JSZip from 'jszip'
import { generateZip, padBlob } from './zip'

describe('padBlob', () => {
  it('appends the padding, its length and the trailer', async () => {
    const padded = padBlob(new Blob(['rec']), 5, 'TRAILER')
    const bytes = new Uint8Array(await padded.arrayBuffer())
    expect(bytes.length).toBe(3 + 5 + 4 + 'TRAILER'.length)
    expect(new TextDecoder().decode(bytes.slice(0, 3))).toBe('rec')
    expect([...bytes.slice(3, 8)]).toEqual([0xaa, 0xaa, 0xaa, 0xaa, 0xaa])
    expect(new DataView(bytes.buffer).getUint32(8, true)).toBe(5)
    expect(new TextDecoder().decode(bytes.slice(12))).toBe('TRAILER')
  })
})

describe('generateZip', () => {
  it('packs the files with the replay packer comment', async () => {
    const blob = await generateZip([
      { name: 'a.txt', content: new Blob(['first']) },
      { name: 'b.txt', content: new Blob(['second']) }
    ])
    const zip = await JSZip.loadAsync(await blob.arrayBuffer())
    expect(Object.keys(zip.files)).toEqual(['a.txt', 'b.txt'])
    expect(await zip.file('b.txt')?.async('string')).toBe('second')
    expect((zip as unknown as { comment: string }).comment).toBe(
      'Generated by https://replaypacker.zeta-two.com'
    )
  })
})
